// Helper to translate any option with safe English fallback
export function getTranslatedOption(optionKey: string, langCode: string): string {
  const map = OPTION_TRANSLATIONS[optionKey];
  if (!map) return optionKey;
  return map[langCode] || map['en'] || optionKey;
}

export function translateMovement(val: MovementType, lang: string): string {
  return getTranslatedOption(val, lang);
}

export function translateCargo(val: CargoType, lang: string): string {
  return getTranslatedOption(val, lang);
}

export function translateVehicle(val: VehicleType, lang: string): string {
  return getTranslatedOption(val, lang);
}

export function translatePriority(val: PriorityLevel, lang: string): string {
  if (val === 'Emergency') return getTranslatedOption('Emergency_prio', lang);
  return getTranslatedOption(val, lang);
}

export function translateRegion(val: IndiaRegion, lang: string): string {
  return getTranslatedOption(val, lang);
}
